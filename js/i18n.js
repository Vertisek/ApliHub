let currentLanguage = localStorage.getItem('aplihub_lang') || 'pl';

function t(key) {
  const dict = I18N_DICTIONARY[currentLanguage] || I18N_DICTIONARY.pl;
  return dict[key] || I18N_DICTIONARY.pl[key] || key;
}

function setAppLanguage(langKey) {
  if (!I18N_DICTIONARY[langKey]) return;
  currentLanguage = langKey;
  localStorage.setItem('aplihub_lang', langKey);
  window.dispatchEvent(new CustomEvent('language_changed', { detail: langKey }));
}

window.t = t;
window.setAppLanguage = setAppLanguage;
